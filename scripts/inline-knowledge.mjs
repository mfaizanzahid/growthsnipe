// Inlines Markdown knowledge (*.md) into a TypeScript module so the Worker
// bundle (esbuild via wrangler, which has no ?raw loader) can import it.
// Run after editing any .md under src/server/sidekick/:  npm run inline-docs
// A sync test (test/knowledge-sync.test.ts) fails if the output is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (rel) => readFileSync(join(root, rel), "utf8");

const entries = {
  workInstructions: "src/server/sidekick/instructions/work-instructions.md",
  coreInstructions: "src/server/sidekick/instructions/core-instructions.md",
  employeeBusinessOwner: "src/server/sidekick/employees/business-owner.md",
  employeeCfo: "src/server/sidekick/employees/cfo.md",
  employeeOperations: "src/server/sidekick/employees/operations-manager.md",
  employeeRevenue: "src/server/sidekick/employees/revenue-manager.md",
  employeeCustomer: "src/server/sidekick/employees/customer-manager.md",
  employeeMarketing: "src/server/sidekick/employees/marketing-analyst.md",
  employeeQuality: "src/server/sidekick/employees/quality-risk-manager.md",
};

const lines = [
  "// AUTO-GENERATED by scripts/inline-knowledge.mjs — do not edit directly.",
  "// Edit the Markdown sources under src/server/sidekick/ and re-run: npm run inline-docs",
  "",
];
for (const [key, rel] of Object.entries(entries)) {
  lines.push(`export const ${key}: string = ${JSON.stringify(read(rel))};`);
  lines.push("");
}
writeFileSync(join(root, "src/server/sidekick/knowledge.ts"), lines.join("\n"));
console.log("knowledge.ts regenerated from", Object.keys(entries).length, "sources");
